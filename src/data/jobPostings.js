/**
 * Retrieve a job posting by unique ID
 */
export function getJobById(id) {
  if (!id) return JOB_POSTINGS[0]
  return JOB_POSTINGS.find((job) => job.id === id) || JOB_POSTINGS[0]
}

/**
 * Retrieve a job posting by URL slug
 */
export function getJobBySlug(slug) {
  if (!slug) return JOB_POSTINGS[0]
  return JOB_POSTINGS.find((job) => job.slug === slug) || JOB_POSTINGS[0]
}
